/** Extract unambiguous List 175 constraints from pinned codelist notes. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

type Entry = { code: string; note?: string };
type Codelist = { number: number; entries: Entry[] };

const root = resolve(import.meta.dirname, "..");

function productForms(note: string): string[] | undefined {
  const match = /use with product form codes?\s+([^.;]+)/i.exec(note);
  return match?.[1]
    .match(/\b[A-Z]{2}\b|\b[A-Z]\*/gi)
    ?.map((value) => value.toUpperCase());
}

function requiredDetails(note: string): string[] | undefined {
  const match = /and product form detail codes?\s+([^.;]+)/i.exec(note);
  return match?.[1]
    .match(/\b[A-Z]\d{3}\b/gi)
    ?.map((value) => value.toUpperCase());
}

async function main(): Promise<void> {
  const codelists = JSON.parse(
    await readFile(resolve(root, "data/generated/codelists.json"), "utf8"),
  ) as Codelist[];
  const details = codelists.find((list) => list.number === 175);
  if (!details) throw new Error("Missing ONIX Code List 175.");
  const rules = details.entries.flatMap((entry) => {
    if (!entry.note) return [];
    const forms = productForms(entry.note);
    if (!forms) return [];
    return [
      {
        detail: entry.code,
        allowedForms: forms.filter((form) => !form.endsWith("*")),
        allowedFormPrefixes: forms
          .filter((form) => form.endsWith("*"))
          .map((form) => form.slice(0, -1)),
        ...(requiredDetails(entry.note)
          ? { requiredDetails: requiredDetails(entry.note) }
          : {}),
        note: entry.note,
      },
    ];
  });
  const audit = details.entries
    .filter((entry) => entry.note)
    .map((entry) => ({
      code: entry.code,
      note: entry.note!,
      extraction: rules.some((rule) => rule.detail === entry.code)
        ? "product-form"
        : "unsupported",
    }));
  await mkdir(resolve(root, "src/generated"), { recursive: true });
  await writeFile(
    resolve(root, "src/generated/semantic-manifest.ts"),
    `// Generated by scripts/generate-semantic-manifest.ts. Do not edit.\nexport const productFormDetailRules = Object.freeze(${JSON.stringify(rules, null, 2)});\n\nexport const productFormDetailRuleAudit = Object.freeze(${JSON.stringify(audit, null, 2)});\n`,
  );
  console.log(
    `Generated ${rules.length} List 175 form rules; recorded ${audit.length - rules.length} unsupported notes.`,
  );
}
await main();
