const parsedDetailRules: readonly SemanticManifestRule[] =
  curatedCodelistDetailRules
    .filter((rule) => !manuallyReviewedDetails.has(rule.detail))
    .map((rule) => ({
      ruleId: `ONIX-175-${rule.detail}-PRODUCT-FORM`,
      source: {
        type: "codelist-note",
        list: 175,
        code: rule.detail,
        text: rule.note,
      },
      sourceClassification: "normative",
      enforcement: "error",
      predicate: {
        kind: "product-form-detail-requires-form",
        details: [rule.detail],
        allowedForms: rule.allowedForms,
        allowedFormPrefixes: rule.allowedFormPrefixes,
        ...(rule.requiredDetails
          ? { requiredDetails: rule.requiredDetails }
          : {}),
      },
    }));

const schemaSource = (
  rule: string,
  text: string,
): SemanticManifestRule["source"] => ({
  type: "schematron",
  rule,
  text,
});

const formRule = (
  ruleId: string,
  details: readonly string[],
  allowedForms: readonly string[],
  source: SemanticManifestRule["source"],
): SemanticManifestRule => ({
  ruleId,
  source,
  sourceClassification: "normative",
  enforcement: "error",
  predicate: {
    kind: "product-form-detail-requires-form",
    details,
    allowedForms,
  },
});

